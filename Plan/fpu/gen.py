#!/usr/bin/env python3
#---------------------------------------------------------------------------
# gen.py : the DSP kernels of step 1.8 U0 (Plan/OOC.md 29.80), written as a
# DSP programmer writes them in assembler, generated here so that the
# register blocking and the unrolling can be varied
#
#   gen.py <dir>        -> <dir>/<kernel>_<variant>_<s|d>.S
#
# Each program: mstatus.FS on, its data made from small integers times 0.25
# (exact in both precisions), the kernel between the labels kstart and kend
# (what fpsched.py measures), then a plain scalar version of the same
# computation and a comparison of the results bit for bit (the same
# operations in the same order for each result, or sums that stay exact);
# HTIF's tohost: 1 passes, 3 fails. Built for rv64gc on SIM/CORE/b2/link.ld.
#
#   dot   ACC 1 / 4 / 8 / 12   sum of a[i] * b[i], 1008 terms, ACC accumulators
#   fir   OUTB 4 / 8 / 12      16 taps, 480 outputs, OUTB outputs at once
#                              (each its own accumulator), coefficients loaded
#   mm    4x4                  32 x 32 matrix product, a 4 x 4 block of C in
#                              16 accumulators, k unrolled by 2
#   bq    CH 1 / 4             biquad (transposed direct form II), 512 samples,
#                              CH channels interleaved
#---------------------------------------------------------------------------
import os
import sys


def prec(d):
    if d:
        return dict(L='fld', S='fsd', MADD='fmadd.d', MUL='fmul.d', ADD='fadd.d', NMSUB='fnmsub.d',
                    CVT='fcvt.d.w', MVZ='fmv.d.x', SZ=8, DIR='.double', LI='ld', SI='sd')
    return dict(L='flw', S='fsw', MADD='fmadd.s', MUL='fmul.s', ADD='fadd.s', NMSUB='fnmsub.s',
                CVT='fcvt.s.w', MVZ='fmv.w.x', SZ=4, DIR='.float', LI='lw', SI='sw')


HEAD = """# {name}: generated by Plan/fpu/gen.py (step 1.8 U0, Plan/OOC.md 29.80)
    .section .text.init
    .globl _start
_start:
    .option norvc                   # (no compressed: fpsched.py decodes the full forms)
    li      t0, 1 << 13
    csrs    mstatus, t0             # FS initial
    csrwi   fcsr, 0
    la      t0, quarter
    {L}     f31, 0(t0)              # 0.25
"""

TAIL = """
pass:
    li      t0, 1
    la      t1, tohost
    sd      t0, 0(t1)
1:  j       1b
fail:
    li      t0, 3
    la      t1, tohost
    sd      t0, 0(t1)
2:  j       2b

    .section .tohost, "aw", @progbits
    .balign 8
    .globl tohost
tohost: .dword 0
    .globl fromhost
fromhost: .dword 0

    .section .data
    .balign 64
quarter: {DIR} 0.25
"""


def fill(p, lab, n, mod, add=0):
    """lab[i] = ((i * 1 + add) % mod) * 0.25 for i < n (f31 holds 0.25)"""
    return f"""    la      a0, {lab}
    li      t0, 0
    li      t6, {n}
    li      t5, {mod}
3:  addi    t1, t0, {add}
    remu    t1, t1, t5
    addi    t1, t1, -{mod // 2}
    {p['CVT']} f0, t1
    {p['MUL']} f0, f0, f31
    {p['S']}     f0, 0(a0)
    addi    a0, a0, {p['SZ']}
    addi    t0, t0, 1
    bltu    t0, t6, 3b
"""


def compare(p, a, b, n):
    """the n results at a and b equal bit for bit"""
    return f"""    la      a0, {a}
    la      a1, {b}
    li      t6, {n}
4:  {p['LI']}      t0, 0(a0)
    {p['LI']}      t1, 0(a1)
    bne     t0, t1, fail
    addi    a0, a0, {p['SZ']}
    addi    a1, a1, {p['SZ']}
    addi    t6, t6, -1
    bnez    t6, 4b
"""


def dot(p, acc):
    n, sz = 1008, p["SZ"]
    s = fill(p, 'va', n, 7) + fill(p, 'vb', n, 5, 2)
    s += "kstart:\n"
    for k in range(acc):
        s += f"    {p['MVZ']} f{k}, zero\n"
    s += f"""    la      a0, va
    la      a1, vb
    li      a2, {n * sz}
    add     a2, a2, a0
5:
"""
    for k in range(acc):
        x, y = 12 + 2 * (k % 9), 13 + 2 * (k % 9)
        s += f"    {p['L']}     f{x}, {k * sz}(a0)\n    {p['L']}     f{y}, {k * sz}(a1)\n"
        s += f"    {p['MADD']} f{k}, f{x}, f{y}, f{k}\n"
    s += f"""    addi    a0, a0, {acc * sz}
    addi    a1, a1, {acc * sz}
    bltu    a0, a2, 5b
"""
    w = acc
    while w > 1:                       # the accumulators summed as a tree
        h = (w + 1) // 2
        for k in range(w - h):
            s += f"    {p['ADD']} f{k}, f{k}, f{k + h}\n"
        w = h
    s += f"""kend:
    la      t0, res
    {p['S']}     f0, 0(t0)
    {p['MVZ']} f1, zero
    la      a0, va
    la      a1, vb
    li      t6, {n}
6:  {p['L']}     f2, 0(a0)
    {p['L']}     f3, 0(a1)
    {p['MADD']} f1, f2, f3, f1
    addi    a0, a0, {sz}
    addi    a1, a1, {sz}
    addi    t6, t6, -1
    bnez    t6, 6b
    la      t0, ref
    {p['S']}     f1, 0(t0)
""" + compare(p, 'res', 'ref', 1) + "    j       pass\n"
    data = f"""va:  .space {n * sz}
vb:  .space {n * sz}
res: .space 8
ref: .space 8
"""
    return s, data


def fir(p, outb):
    t, n, sz = 16, 480, p['SZ']
    s = fill(p, 'vx', n + t, 9) + fill(p, 'vh', t, 5, 1)
    s += f"""kstart:
    la      a0, vx
    la      a1, vh
    la      a3, vy
    li      a2, {n * sz}
    add     a2, a2, a3
5:
"""
    for j in range(outb):
        s += f"    {p['MVZ']} f{j}, zero\n"
    r = 0
    for k in range(t):
        h = 12 + (k % 4)
        s += f"    {p['L']}     f{h}, {k * sz}(a1)\n"
        for j in range(outb):
            x = 16 + (r % 15)
            r += 1
            s += f"    {p['L']}     f{x}, {(k + j) * sz}(a0)\n    {p['MADD']} f{j}, f{h}, f{x}, f{j}\n"
    for j in range(outb):
        s += f"    {p['S']}     f{j}, {j * sz}(a3)\n"
    s += f"""    addi    a0, a0, {outb * sz}
    addi    a3, a3, {outb * sz}
    bltu    a3, a2, 5b
kend:
    la      a0, vx
    la      a3, vr
    li      t6, {n}
6:  {p['MVZ']} f0, zero
    la      a1, vh
    mv      a4, a0
    li      t5, {t}
7:  {p['L']}     f1, 0(a1)
    {p['L']}     f2, 0(a4)
    {p['MADD']} f0, f1, f2, f0
    addi    a1, a1, {sz}
    addi    a4, a4, {sz}
    addi    t5, t5, -1
    bnez    t5, 7b
    {p['S']}     f0, 0(a3)
    addi    a0, a0, {sz}
    addi    a3, a3, {sz}
    addi    t6, t6, -1
    bnez    t6, 6b
""" + compare(p, 'vy', 'vr', n) + "    j       pass\n"
    data = f"""vx:  .space {(n + t) * sz}
vh:  .space {t * sz}
vy:  .space {n * sz}
vr:  .space {n * sz}
"""
    return s, data


def mm(p):
    m, sz = 32, p['SZ']
    s = fill(p, 'ma', m * m, 7) + fill(p, 'mb', m * m, 5, 3)
    s += f"""kstart:
    la      s0, ma
    la      s2, mc
    li      s4, 0                   # i0
8:  li      s5, 0                   # j0
9:
"""
    for k in range(16):
        s += f"    {p['MVZ']} f{k}, zero\n"
    # a0: &A[i0][0] (rows i0..i0+3 at +m*sz), a1: &B[0][j0], a2: the end of the k loop
    s += f"""    li      t0, {m * sz}
    mul     t1, s4, t0
    add     a0, s0, t1              # &A[i0][0]
    la      a1, mb
    slli    t2, s5, {3 if sz == 8 else 2}
    add     a1, a1, t2              # &B[0][j0]
    addi    a2, a0, {m * sz}        # the end of row i0
5:
"""
    for u in range(2):
        av = [16 + 8 * u + r for r in range(4)]
        bv = [20 + 8 * u + c for c in range(4)]
        for r in range(4):
            s += f"    {p['L']}     f{av[r]}, {r * m * sz + u * sz}(a0)\n"
        for c in range(4):
            s += f"    {p['L']}     f{bv[c]}, {u * m * sz + c * sz}(a1)\n"
        for r in range(4):
            for c in range(4):
                s += f"    {p['MADD']} f{4 * r + c}, f{av[r]}, f{bv[c]}, f{4 * r + c}\n"
    s += f"""    addi    a0, a0, {2 * sz}
    addi    a1, a1, {2 * m * sz}
    bltu    a0, a2, 5b
    li      t0, {m * sz}
    mul     t1, s4, t0
    add     a3, s2, t1
    slli    t2, s5, {3 if sz == 8 else 2}
    add     a3, a3, t2              # &C[i0][j0]
"""
    for r in range(4):
        for c in range(4):
            s += f"    {p['S']}     f{4 * r + c}, {r * m * sz + c * sz}(a3)\n"
    s += f"""    addi    s5, s5, 4
    li      t0, {m}
    bltu    s5, t0, 9b
    addi    s4, s4, 4
    bltu    s4, t0, 8b
kend:
    li      s4, 0                   # i
10: li      s5, 0                   # j
11: {p['MVZ']} f0, zero
    li      t0, {m * sz}
    mul     t1, s4, t0
    la      a0, ma
    add     a0, a0, t1              # &A[i][0]
    la      a1, mb
    slli    t2, s5, {3 if sz == 8 else 2}
    add     a1, a1, t2              # &B[0][j]
    li      t5, {m}
12: {p['L']}     f1, 0(a0)
    {p['L']}     f2, 0(a1)
    {p['MADD']} f0, f1, f2, f0
    addi    a0, a0, {sz}
    addi    a1, a1, {m * sz}
    addi    t5, t5, -1
    bnez    t5, 12b
    la      a3, mr
    add     a3, a3, t1
    add     a3, a3, t2
    {p['S']}     f0, 0(a3)
    addi    s5, s5, 1
    li      t0, {m}
    bltu    s5, t0, 11b
    addi    s4, s4, 1
    bltu    s4, t0, 10b
""" + compare(p, 'mc', 'mr', m * m) + "    j       pass\n"
    data = f"""ma:  .space {m * m * sz}
mb:  .space {m * m * sz}
mc:  .space {m * m * sz}
mr:  .space {m * m * sz}
"""
    return s, data


def bq(p, ch):
    n, sz = 512, p['SZ']
    s = fill(p, 'bx', n * ch, 11)
    # coefficients: b0 0.5, b1 0.25, b2 0.125, a1 0.5, a2 0.25 (f26..f30)
    s += f"""    la      t0, coef
    {p['L']}     f26, 0(t0)
    {p['L']}     f27, {sz}(t0)
    {p['L']}     f28, {2 * sz}(t0)
    {p['L']}     f29, {3 * sz}(t0)
    {p['L']}     f30, {4 * sz}(t0)
kstart:
"""
    # channel c: s1 f(2c), s2 f(2c+1); temporaries rotate in f8..f25
    for c in range(ch):
        s += f"    {p['MVZ']} f{2 * c}, zero\n    {p['MVZ']} f{2 * c + 1}, zero\n"
    s += f"""    la      a0, bx
    la      a3, by
    li      a2, {n * ch * sz}
    add     a2, a2, a0
5:
"""
    r = 0

    def tmp():
        nonlocal r
        v = 8 + (r % 18)
        r += 1
        return v
    for c in range(ch):
        x, y, t, t2 = tmp(), tmp(), tmp(), tmp()
        s1, s2 = 2 * c, 2 * c + 1
        s += f"""    {p['L']}     f{x}, {c * sz}(a0)
    {p['MADD']} f{y}, f26, f{x}, f{s1}
    {p['MADD']} f{t}, f27, f{x}, f{s2}
    {p['NMSUB']} f{s1}, f29, f{y}, f{t}
    {p['MUL']} f{t2}, f28, f{x}
    {p['NMSUB']} f{s2}, f30, f{y}, f{t2}
    {p['S']}     f{y}, {c * sz}(a3)
"""
    s += f"""    addi    a0, a0, {ch * sz}
    addi    a3, a3, {ch * sz}
    bltu    a0, a2, 5b
kend:
    li      s4, 0                   # channel
13: {p['MVZ']} f0, zero
    {p['MVZ']} f1, zero
    la      a0, bx
    la      a3, br
    slli    t0, s4, {3 if sz == 8 else 2}
    add     a0, a0, t0
    add     a3, a3, t0
    li      t5, {n}
14: {p['L']}     f8, 0(a0)
    {p['MADD']} f9, f26, f8, f0
    {p['MADD']} f10, f27, f8, f1
    {p['NMSUB']} f0, f29, f9, f10
    {p['MUL']} f11, f28, f8
    {p['NMSUB']} f1, f30, f9, f11
    {p['S']}     f9, 0(a3)
    addi    a0, a0, {ch * sz}
    addi    a3, a3, {ch * sz}
    addi    t5, t5, -1
    bnez    t5, 14b
    addi    s4, s4, 1
    li      t0, {ch}
    bltu    s4, t0, 13b
""" + compare(p, 'by', 'br', n * ch) + "    j       pass\n"
    data = f"""coef: {p['DIR']} 0.5, 0.25, 0.125, 0.5, 0.25
bx:  .space {n * ch * sz}
by:  .space {n * ch * sz}
br:  .space {n * ch * sz}
"""
    return s, data


KERNELS = ([('dot', 'acc%d' % a, lambda p, a=a: dot(p, a)) for a in (1, 4, 8, 12)] +
           [('fir', 'out%d' % o, lambda p, o=o: fir(p, o)) for o in (4, 8, 12)] +
           [('mm', '4x4', mm)] +
           [('bq', 'ch%d' % c, lambda p, c=c: bq(p, c)) for c in (1, 4)])

if __name__ == '__main__':
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    for kname, var, f in KERNELS:
        for d in (0, 1):
            p = prec(d)
            name = f"{kname}_{var}_{'d' if d else 's'}"
            body, data = f(p)
            src = HEAD.format(name=name, **p) + body + TAIL.format(**p) + data
            open(os.path.join(out, name + '.S'), 'w').write(src)
            print(name)
