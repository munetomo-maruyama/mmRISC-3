#!/usr/bin/env python3
#---------------------------------------------------------------------------
# gen_chase.py : the pointer chase of LitexSystem/software/dramlat for
#                tb_core (step 2.5, the memory model's calibration,
#                LitexSystem/docs/BRINGUP.md 27)
#
#   python3 gen_chase.py <KB> random|linear > chase.S
#
# One 8-byte load at the start of each 64-byte line of <KB> KB, each load's
# address the previous load's data: the lines in a random single cycle
# (Sattolo, a fixed seed) or in address order. A warm pass over every line,
# then the timed one (start_time to stop_time, tb_core -v): every line once,
# so the window over the line count is the cycles of one load.
#---------------------------------------------------------------------------
import random, sys
kb, order = int(sys.argv[1]), sys.argv[2]
n = kb * 1024 // 64
perm = list(range(n))
if order == "random":
    r = random.Random(1)
    for i in range(n - 1, 0, -1):          # Sattolo: a single cycle
        j = r.randrange(i)
        perm[i], perm[j] = perm[j], perm[i]
else:
    perm = [(i + 1) % n for i in range(n)]
loop = "\n".join(["    ld      a0, 0(a0)"] * 8)
print(f"""# generated by gen_chase.py {kb} {order}: {n} lines
    .section .text.init
    .globl _start
_start:
    la      a0, area
    li      t1, {n // 8}
1:
{loop}
    addi    t1, t1, -1
    bnez    t1, 1b
    li      t1, {n // 8}
    .globl start_time
start_time:
2:
{loop}
    addi    t1, t1, -1
    bnez    t1, 2b
    .globl stop_time
stop_time:
    li      t0, 1
    la      t1, tohost
    sd      t0, 0(t1)
8:  j       8b

    .section .tohost, "aw", @progbits
    .balign 8
    .globl tohost
tohost: .dword 0
    .globl fromhost
fromhost: .dword 0

    .section .data
    .balign 64
area:""")
for i in range(n):
    print(f"    .dword area + {64 * perm[i]}\n    .space 56")
